def split_ingredients(items):
    """'Название — количество' -> {name, amount}."""
    out = []
    for it in items:
        if "—" in it:
            name, amount = it.split("—", 1)
            out.append({"name": name.strip(), "amount": amount.strip()})
        else:
            out.append({"name": it.strip(), "amount": ""})
    return out



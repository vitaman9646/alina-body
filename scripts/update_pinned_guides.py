#!/usr/bin/env python3
"""Обновляет закреп в канале: альбом карточек + лонгрид (пин)."""
import os, json, urllib.request, urllib.parse

def load_env():
    e = {}
    for line in open(os.path.expanduser("~/credentials/telegram.env")):
        line = line.strip()
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1); e[k.strip()] = v.strip()
    return e

env = load_env()
TOKEN = env["TELEGRAM_BOT_TOKEN"]
CH = env["TELEGRAM_CHANNEL_ID"]

def api(method, **params):
    data = urllib.parse.urlencode(params).encode()
    req = urllib.request.Request(f"https://api.telegram.org/bot{TOKEN}/{method}", data=data)
    return json.loads(urllib.request.urlopen(req, timeout=40).read())

def send_album(urls):
    media = [{"type": "photo", "media": u, "caption": "" if i else ""} for i, u in enumerate(urls)]
    return api("sendMediaGroup", chat_id=CH, media=json.dumps(media))

def send_and_pin(text):
    r = api("sendMessage", chat_id=CH, text=text, parse_mode="HTML", disable_web_page_preview="true")
    mid = r["result"]["message_id"]
    api("pinChatMessage", chat_id=CH, message_id=mid)
    return mid


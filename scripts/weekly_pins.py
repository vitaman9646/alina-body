#!/usr/bin/env python3
"""Weekly v2-variant pins CSV — generates and SENDS to Vitaliy via Telegram.

Runs every Sunday. Finds content created since the last run (state file),
generates the 2nd pin (v2) for each new article (excerpt as title + rotated
char photo) and picks up new lead magnets' v2 pins, writes the CSV and sends it
to Vitaliy's Telegram chat via sendDocument.

Idempotent: state file content/weekly_pins_state.json records sent slugs.

Usage: python3 scripts/weekly_pins.py [--dry-run] [--no-send]
Runs under .venv-tts/bin/python (needs Pillow + requests).
"""
import csv
import io
import json
import os
import sys
from datetime import datetime

import requests

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_pins import build_pin, resolve_source, load_creds  # noqa: E402

REPO = "/home/hermes/alina-body"
STATE = f"{REPO}/content/weekly_pins_state.json"
PIN_BASE = "https://tmzoyfhcajnukqotqspp.supabase.co/storage/v1/object/public/alina-media/pinterest"
VITALIY_CHAT = "1066756284"

# char photo rotation for article v2 (different from the v1 cover)
CHAR_POOL = ["squat.jpg", "lunge.jpg", "plank.jpg", "stretch.jpg", "resistance-band.jpg",
             "side-plank.jpg", "sportswear.jpg", "casual.jpg", "confident.jpg", "glute-bridge.jpg",
             "post-workout.jpg", "outdoor.jpg"]

BOARD_RE = [
    # NB: «еда» нельзя — ловится внутри «сЕДАешь» (приседание). Только длинные специфичные токены.
    (r"суп|салат|белок|питани|калори|меню|рацион|рецепт|продукт|кбжу|завтрак|обед|ужин|десерт", "Питание и рецепты"),
    (r"цикл|сон|привычк|мотивац|бросить|стресс|здоровь|печен|целлюлит|шаг|ходьб|вечер|крепатур", "Здоровье и привычки"),
]


def board_for(title):
    t = (title or "").lower()
    for pat, board in BOARD_RE:
        for w in pat.split("|"):
            if w in t:
                return board
    return "Тренировки дома"


def load_env(path):
    d = {}
    for line in open(path):
        line = line.strip()
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            d[k] = v
    return d


def main():
    dry = "--dry-run" in sys.argv
    no_send = "--no-send" in sys.argv

    supa = load_env(os.path.expanduser("~/credentials/threads.env"))
    tg = load_env(os.path.expanduser("~/credentials/telegram.env"))
    supa_url, supa_key = supa["SUPABASE_URL"], supa["SUPABASE_SERVICE_ROLE_KEY"]
    bot = tg["TELEGRAM_BOT_TOKEN"]

    state = json.load(open(STATE)) if os.path.exists(STATE) else {"articles": [], "magnets": []}

    rows = []
    # --- 1. new articles -> v2 pin (excerpt as title + rotated photo) ---
    posts = requests.get(
        f"{supa_url}/rest/v1/posts?select=slug,title,excerpt&order=published_at.desc&limit=60",
        headers={"apikey": supa_key, "Authorization": f"Bearer {supa_key}"}, timeout=30,
    ).json()

    for idx, p in enumerate(posts):
        slug = p["slug"]
        if slug in state["articles"]:
            continue
        excerpt = (p.get("excerpt") or p["title"]).strip()
        v2_title = excerpt[:90]
        v2_file = f"pin-{slug}-v2.jpg"
        char = CHAR_POOL[idx % len(CHAR_POOL)]

        if not dry:
            try:
                img, mode = resolve_source(f"char/{char}")
                out = build_pin(img, mode, v2_title)
                buf = io.BytesIO()
                out.save(buf, "JPEG", quality=88, optimize=True)
                requests.post(
                    f"{supa_url}/storage/v1/object/alina-media/pinterest/{v2_file}",
                    headers={"Authorization": f"Bearer {supa_key}", "apikey": supa_key,
                             "x-upsert": "true", "Content-Type": "image/jpeg"},
                    data=buf.getvalue(), timeout=120,
                )
            except Exception as e:
                print(f"SKIP {slug}: {e}")
                continue

        rows.append({
            "Title": v2_title,
            "Media URL": f"{PIN_BASE}/{v2_file}",
            "Pinterest board": board_for(p["title"]),
            "Thumbnail": "",
            "Description": p["title"],
            "Link": f"https://alina-body.fitness/blog/{slug}",
            "Publish date": "",
            "Keywords": f"{v2_title.lower()}, тренировки дома, фитнес для женщин",
        })
        state["articles"].append(slug)

    # --- 2. new lead magnets -> v2 pin (already generated by gen_lead_pins.py) ---
    try:
        sys.path.insert(0, REPO + "/scripts")
        from gen_lead_pins import LEAD_MAGNETS
        for slug, meta in LEAD_MAGNETS.items():
            if slug in state["magnets"]:
                continue
            if len(meta["pins"]) < 2:
                state["magnets"].append(slug)
                continue
            _v, title, tagline, _ill = meta["pins"][1]
            rows.append({
                "Title": title,
                "Media URL": f"{PIN_BASE}/lead-{slug}-v2.jpg",
                "Pinterest board": meta["board"],
                "Thumbnail": "",
                "Description": tagline,
                "Link": meta["landing"],
                "Publish date": "",
                "Keywords": f"{title.lower()}, {meta['board'].lower()}",
            })
            state["magnets"].append(slug)
    except Exception as e:
        print(f"lead magnets skip: {e}")

    if dry:
        print(f"[dry] {len(rows)} pins would be sent")
        for r in rows:
            print("  ", r["Title"][:50], "->", r["Pinterest board"])
        return

    if not rows:
        print("Нет нового контента для CSV.")
        return

    # --- write CSV ---
    stamp = datetime.now().strftime("%Y-%m-%d")
    csv_path = f"{REPO}/content/weekly_pins_{stamp}.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["Title", "Media URL", "Pinterest board", "Thumbnail",
                                          "Description", "Link", "Publish date", "Keywords"])
        w.writeheader()
        w.writerows(rows)

    json.dump(state, open(STATE, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"CSV: {csv_path} ({len(rows)} pins)")

    # --- send to Vitaliy via Telegram ---
    if not no_send:
        with open(csv_path, "rb") as f:
            r = requests.post(
                f"https://api.telegram.org/bot{bot}/sendDocument",
                data={"chat_id": VITALIY_CHAT, "caption": f"Пины за неделю ({len(rows)} шт) — залей через Bulk create Pins"},
                files={"document": (os.path.basename(csv_path), f, "text/csv")},
                timeout=60,
            )
        print("Telegram send:", r.status_code, r.text[:200])


if __name__ == "__main__":
    main()

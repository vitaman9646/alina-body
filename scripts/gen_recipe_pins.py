#!/usr/bin/env python3
"""Generate Pinterest pins for the 17 ПП-рецепты (dish photo + recipe name overlay).

Reuses gen_pins.build_pin (cover-crop + gradient + title). Dish photos come from
alina-media/recipes-photo/<slug>.jpg (generated by gen_recipe_photos.py).

Usage: python3 scripts/gen_recipe_pins.py [--dry-run]
"""
import io
import json
import os
import sys

import requests

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_pins import build_pin, resolve_source, load_creds  # noqa: E402
from gen_recipe_photos import slugify  # noqa: E402

SRC = "/tmp/recipes_all.json"


def main():
    dry = "--dry-run" in sys.argv
    url, key = load_creds()
    recipes = json.load(open(SRC))

    made = 0
    for r in recipes:
        name = r["name"]
        slug = r.get("slug") or slugify(name)
        fname = f"recipe-{slug}.jpg"
        if dry:
            print(f"[dry] {fname} <- {name}")
            made += 1
            continue
        try:
            img, mode = resolve_source(f"recipes-photo/{slug}.jpg")
            out = build_pin(img, mode, name)
        except Exception as e:
            print(f"SKIP {name}: {e}")
            continue
        buf = io.BytesIO()
        out.save(buf, "JPEG", quality=88, optimize=True)
        up = requests.post(
            f"{url}/storage/v1/object/alina-media/pinterest/{fname}",
            headers={
                "Authorization": f"Bearer {key}", "apikey": key,
                "x-upsert": "true", "Content-Type": "image/jpeg",
            },
            data=buf.getvalue(), timeout=120,
        )
        status = "uploaded" if up.status_code in (200, 201) else f"FAIL {up.status_code}"
        print(f"[+] {fname} <- {name}  {status}")
        made += 1

    print(f"\nDone: {made} recipe pins")


if __name__ == "__main__":
    main()

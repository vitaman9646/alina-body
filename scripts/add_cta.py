#!/usr/bin/env python3
"""Добавляет CTA «напишите „чеклист“ → получите материал» в конверсионные посты."""
import re

CTA = "напишите «чеклист» в комментарии — пришлю бесплатный чеклист"
IG_CTA = "Напишите «чеклист» в комментарии — пришлю бесплатный чеклист в личные сообщения 💕"
TH_CTA = "Напишите «чеклист» в комментарии — пришлю бесплатный чеклист 💕"

# === Instagram: заменяем «Ссылка в шапке профиля.» на CTA ===
ig = open("content_plan_instagram.md", encoding="utf-8").read()
n = ig.count("Ссылка в шапке профиля.")
ig = ig.replace("Ссылка в шапке профиля.", IG_CTA)
open("content_plan_instagram.md", "w", encoding="utf-8").write(ig)
print(f"IG: заменено CTA — {n}")

# === Threads: 💬 Реплай → CTA, и хвосты «Пост:» → CTA ===
t = open("content_plan.md", encoding="utf-8").read()

# 💬 Реплай (любой текст) → CTA-подсказка
n1 = len(re.findall(r"💬 Реплай:", t))
t = re.sub(r'💬 Реплай: ".*?"', f'💬 Реплай: "{TH_CTA}"', t)

# хвосты «Пост:» (от частного к общему)
reps = [
    ("можно по ссылке ниже.", CTA + "."),
    ("загляните по ссылке ниже.", CTA + "."),
    ("в канале — ссылка ниже.", CTA + "."),
    ("в канале, ссылка ниже.", CTA + "."),
    ("— по ссылке ниже.", " — " + CTA + "."),
    ("по ссылке ниже.", CTA + "."),
    ("— ссылка ниже.", " — " + CTA + "."),
    ("ссылка ниже.", CTA + "."),
]
n2 = 0
for old, new in reps:
    cnt = t.count(old)
    n2 += cnt
    t = t.replace(old, new)

open("content_plan.md", "w", encoding="utf-8").write(t)
print(f"Threads: 💬 Реплай заменено — {n1}, хвостов Пост: заменено — {n2}")
print("осталось «ссылка» в Пост::", len(re.findall(r"Пост:.*ссылка", t)))

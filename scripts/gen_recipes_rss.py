#!/usr/bin/env python3
"""Generate public/recipes.xml — RSS for recipes.

Pinterest auto-imports it so every new recipe auto-pins (pin image = recipe-<slug>.jpg
with name overlay, generated by gen_recipe_pins.py). Reads public/recipes.json.

Usage: python3 scripts/gen_recipes_rss.py
"""
import json
import os
from datetime import datetime, timezone

SITE = "https://alina-body.fitness"
PIN_BASE = "https://tmzoyfhcajnukqotqspp.supabase.co/storage/v1/object/public/alina-media/pinterest"
SRC = "/home/hermes/alina-body/public/recipes.json"
OUT = "/home/hermes/alina-body/public/recipes.xml"


def esc(s):
    return (str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;"))


PUBDATES = "/home/hermes/alina-body/content/feed_pubdates.json"


def get_pubdate(key):
    """Стабильный pubDate на слага (первый раз — сейчас, дальше не меняется)."""
    try:
        st = json.load(open(PUBDATES))
    except (OSError, json.JSONDecodeError):
        st = {}
    if key not in st:
        st[key] = datetime.now(timezone.utc).strftime("%a, %d %b %Y %H:%M:%S GMT")
        try:
            json.dump(st, open(PUBDATES, "w"), ensure_ascii=False, indent=2)
        except OSError:
            pass
    return st[key]


def main():
    recipes = json.load(open(SRC))
    items = []
    for r in recipes:
        slug = r["slug"]
        name = r["name"]
        link = f"{SITE}/recipe/{slug}"
        img = f"{PIN_BASE}/recipe-{slug}.jpg"
        desc = f"{name} — простой ПП-рецепт: ингредиенты и пошаговое приготовление."
        pd = get_pubdate(f"recipe-{slug}")
        items.append(
            f"    <item>\n"
            f"      <title><![CDATA[{name}]]></title>\n"
            f"      <link>{link}</link>\n"
            f"      <guid isPermaLink=\"true\">{link}</guid>\n"
            f"      <pubDate>{pd}</pubDate>\n"
            f"      <description><![CDATA[{desc}]]></description>\n"
            f"      <media:content url=\"{img}\" medium=\"image\">\n"
            f"        <media:title type=\"plain\">{name}</media:title>\n"
            f"      </media:content>\n"
            f"      <category>recipe</category>\n"
            f"    </item>"
        )

    last_build = datetime.now(timezone.utc).strftime("%a, %d %b %Y %H:%M:%S GMT")
    rss = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<rss version="2.0" xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:media="http://search.yahoo.com/mrss/">\n'
        "  <channel>\n"
        "    <title>Alina Body — ПП-рецепты</title>\n"
        f"    <link>{SITE}</link>\n"
        "    <description>Простые ПП-рецепты от Алины — завтраки, обеды, ужины и десерты.</description>\n"
        "    <language>ru</language>\n"
        f"    <lastBuildDate>{last_build}</lastBuildDate>\n"
        f'    <atom:link href="{SITE}/recipes.xml" rel="self" type="application/rss+xml" xmlns:atom="http://www.w3.org/2005/Atom"/>\n'
        f"    {chr(10).join(items)}\n"
        "  </channel>\n"
        "</rss>"
    )
    open(OUT, "w", encoding="utf-8").write(rss)
    print(f"Wrote {len(items)} recipes -> {OUT}")


if __name__ == "__main__":
    main()
